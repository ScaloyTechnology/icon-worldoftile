// Every collection overview appears in the bottom selector automatically.
// Interior camera positions use navId and stay grouped under that collection.
export const roomOrder = Object.values(rooms)
  .filter((room) => !room.navId && room.showInNavigation !== false)
  .sort((a, b) => Number(a.index) - Number(b.index))
  .map((room) => room.id);
export const initialRoomId = roomOrder[0];

export function getAdjacentRoomIds(roomId) {
  const room = rooms[roomId];
  return [...new Set([
    ...(room.adjacentRooms || []),
    ...room.hotspots
      .filter((hotspot) => hotspot.type === "room")
      .map((hotspot) => hotspot.targetRoom),
  ])].filter((id) => rooms[id]?.panorama && !rooms[id].pending);
}
