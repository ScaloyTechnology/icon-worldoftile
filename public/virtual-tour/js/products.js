export class ProductPanel {
  constructor({ panel, onOpen, onClose }) {
    this.panel = panel;
    this.onOpen = onOpen;
    this.onClose = onClose;
    this.closeButton = document.querySelector("#product-close");
    this.previouslyFocused = null;

    this.fields = {
      image: document.querySelector("#product-image"),
      caption: document.querySelector("#product-image-caption"),
      collection: document.querySelector("#product-collection"),
      name: document.querySelector("#product-name"),
      description: document.querySelector("#product-description"),
      dimensions: document.querySelector("#product-dimensions"),
      finish: document.querySelector("#product-finish"),
      material: document.querySelector("#product-material"),
    };

    this.closeButton.addEventListener("click", () => this.close());
    document.addEventListener("keydown", (event) => {
      if (event.key === "Escape" && this.isOpen) this.close();
    });
  }

  get isOpen() {
    return this.panel.classList.contains("is-open");
  }

  open(productId, trigger) {
    const product = products[productId];
    if (!product) return;

    this.previouslyFocused = trigger || document.activeElement;
    this.fields.image.src = product.image;
    this.fields.image.alt = product.imageAlt;
    this.fields.caption.textContent = `${product.name} / material detail`;
    this.fields.collection.textContent = product.collection;
    this.fields.name.textContent = product.name;
    this.fields.description.textContent = product.description;
    this.fields.dimensions.textContent = product.dimensions;
    this.fields.finish.textContent = product.finish;
    this.fields.material.textContent = product.material;

    this.panel.classList.add("is-open");
    this.panel.setAttribute("aria-hidden", "false");
    this.onOpen?.(product);
    window.setTimeout(() => this.closeButton.focus(), 320);
  }

  close() {
    if (!this.isOpen) return;
    this.panel.classList.remove("is-open");
    this.panel.setAttribute("aria-hidden", "true");
    this.onClose?.();
    window.setTimeout(() => this.previouslyFocused?.focus?.(), 500);
  }
}
